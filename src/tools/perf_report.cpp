#include <cstdio>
#include <fstream>
#include <sstream>
#include <stdexcept>

#include "dispatchlab/json.hpp"
#include "dispatchlab/tools.hpp"

namespace dispatchlab {

namespace {

constexpr const char* kBegin = "<!-- BEGIN GENERATED -->";
constexpr const char* kEnd = "<!-- END GENERATED -->";

std::string f(double v, int prec = 1) {
    char buf[64];
    std::snprintf(buf, sizeof buf, "%.*f", prec, v);
    return buf;
}

std::string mib(double bytes) { return f(bytes / 1048576.0, 2) + " MiB"; }
std::string kib(double bytes) { return f(bytes / 1024.0, 1) + " KiB"; }

std::string default_prose() {
    return "# DispatchLab performance report\n\n"
           "All numbers below are produced by `./scripts/verify.sh` (benchmarks in `benchmarks/`) and are "
           "regenerated on every run; only the analysis section is hand-written.\n\n" +
           std::string(kBegin) + "\n" + kEnd + "\n";
}

}  // namespace

void write_performance_report(const std::string& graph_json, const std::string& routing_json,
                              const std::string& dispatch_json, const std::string& experiments_md,
                              const std::string& out_path) {
    const json::Value G = json::parse_file(graph_json);
    const json::Value R = json::parse_file(routing_json);
    const json::Value D = json::parse_file(dispatch_json);
    const json::Value& env = R.at("environment");
    const json::Value& ds = R.at("dataset");

    std::ostringstream md;
    md << kBegin << "\n";
    md << "<!-- Generated by `dispatchlab perf-report`; edits inside this block are overwritten. -->\n\n";
    md << "## Environment and methodology\n\n";
    md << "| Item | Value |\n|---|---|\n";
    md << "| Hardware | " << env.at("cpu").as_string() << ", " << env.at("logical_cores").as_int() << " logical cores, "
       << f(env.at("memory_bytes").as_double() / 1073741824.0, 0) << " GiB RAM |\n";
    md << "| OS | " << env.at("os").as_string() << " |\n";
    md << "| Compiler | " << env.at("compiler").as_string() << " |\n";
    md << "| Build type | " << env.at("build_type").as_string() << " |\n";
    md << "| Flags | `" << env.at("cxx_flags").as_string() << " -std=c++20` |\n";
    md << "| Dataset | " << ds.at("source").as_string() << " |\n";
    md << "| Graph | " << ds.at("nodes").as_int() << " nodes, " << ds.at("edges").as_int()
       << " directed edges (largest SCC), v_max = " << ds.at("max_speed_kmh").as_int() << " km/h |\n";
    md << "| Seed | " << R.at("seed").as_int() << " (routing/graph), " << D.at("seed").as_int() << " (dispatch) |\n";
    md << "| Run at | " << env.at("timestamp_utc").as_string() << " |\n\n";
    md << "Methodology:\n\n";
    md << "- Routing: " << R.at("methodology").as_string() << ". " << R.at("queries").as_int() << " measured queries.\n";
    md << "- Graph: " << G.at("methodology").as_string() << ".\n";
    md << "- Dispatch: " << D.at("methodology").as_string() << ".\n";
    md << "- Latency percentiles are nearest-rank. Timings are wall-clock (`std::chrono::steady_clock`) on a "
          "non-isolated machine, so expect run-to-run noise of several percent.\n\n";

    // ---- graph
    const json::Value& c = G.at("csr");
    const json::Value& a = G.at("adjacency");
    md << "## Graph representation: CSR vs adjacency list\n\n";
    md << "| Metric | CSR | Adjacency list | Adjacency / CSR |\n|---|---:|---:|---:|\n";
    auto row = [&](const char* name, const std::string& cv, const std::string& av, double ratio) {
        md << "| " << name << " | " << cv << " | " << av << " | " << f(ratio, 2) << "x |\n";
    };
    row("Memory (forward topology + weights)", mib(c.at("memory_bytes").as_double()), mib(a.at("memory_bytes").as_double()),
        a.at("memory_bytes").as_double() / c.at("memory_bytes").as_double());
    row("Load from binary file (ms)", f(c.at("load_ms").as_double()), f(a.at("load_ms").as_double()),
        a.at("load_ms").as_double() / c.at("load_ms").as_double());
    row("Construction from edge list (ms)", f(c.at("build_ms").as_double()), f(a.at("build_ms").as_double()),
        a.at("build_ms").as_double() / c.at("build_ms").as_double());
    row("Sequential traversal of all edges (ms)", f(c.at("traversal_ms").as_double(), 3),
        f(a.at("traversal_ms").as_double(), 3), a.at("traversal_ms").as_double() / c.at("traversal_ms").as_double());
    row("Sequential traversal (ns/edge)", f(c.at("traversal_ns_per_edge").as_double(), 2),
        f(a.at("traversal_ns_per_edge").as_double(), 2),
        a.at("traversal_ns_per_edge").as_double() / c.at("traversal_ns_per_edge").as_double());
    row("Dijkstra query, median (us)", f(c.at("dijkstra_median_us").as_double(), 0),
        f(a.at("dijkstra_median_us").as_double(), 0),
        a.at("dijkstra_median_us").as_double() / c.at("dijkstra_median_us").as_double());
    row("Dijkstra query, p95 (us)", f(c.at("dijkstra_p95_us").as_double(), 0), f(a.at("dijkstra_p95_us").as_double(), 0),
        a.at("dijkstra_p95_us").as_double() / c.at("dijkstra_p95_us").as_double());
    md << "\nCSR load time includes building the reverse CSR (" << f(G.at("reverse_build_ms").as_double())
       << " ms median) and full validation; the adjacency list is forward-only. Full `Graph` object (forward + "
          "reverse CSR, lengths, classes, coordinates, OSM ids): "
       << mib(G.at("full_graph_memory_bytes").as_double()) << ". Benchmark peak RSS: "
       << mib(G.at("peak_rss_bytes").as_double()) << ".\n\n";

    // ---- routing
    md << "## Routing algorithms (same " << R.at("queries").as_int() << " seeded queries)\n\n";
    md << "| Algorithm | Median (us) | p95 (us) | p99 (us) | Mean (us) | Nodes settled (median) | Nodes settled (mean) | "
          "Memory (per-query workspace) | Median latency vs Dijkstra |\n";
    md << "|---|---:|---:|---:|---:|---:|---:|---:|---:|\n";
    const auto& algs = R.at("algorithms").as_array();
    const double base = algs.at(0).at("median_us").as_double();
    for (const auto& x : algs) {
        md << "| " << x.at("name").as_string() << " | " << f(x.at("median_us").as_double()) << " | "
           << f(x.at("p95_us").as_double()) << " | " << f(x.at("p99_us").as_double()) << " | "
           << f(x.at("mean_us").as_double()) << " | " << f(x.at("settled_median").as_double(), 0) << " | "
           << f(x.at("settled_mean").as_double(), 0) << " | " << kib(x.at("memory_bytes").as_double()) << " | "
           << f(base / x.at("median_us").as_double(), 2) << "x |\n";
    }
    md << "\nThe shared graph (" << mib(R.at("graph_memory_bytes").as_double())
       << ") is excluded from per-algorithm memory. Bidirectional keeps two label sets and two heaps.\n\n";
    md << "By travel-time distance (Dijkstra cost):\n\n";
    md << "| Distance | Queries | Dijkstra median (us) | Bidirectional median (us) | A* median (us) | Dijkstra settled | "
          "Bidirectional settled | A* settled |\n|---|---:|---:|---:|---:|---:|---:|---:|\n";
    for (const auto& b : R.at("buckets").as_array()) {
        md << "| " << b.at("label").as_string() << " | " << b.at("count").as_int() << " | "
           << f(b.at("dijkstra_median_us").as_double()) << " | " << f(b.at("bidirectional_median_us").as_double())
           << " | " << f(b.at("astar_median_us").as_double()) << " | "
           << f(b.at("dijkstra_settled_median").as_double(), 0) << " | "
           << f(b.at("bidirectional_settled_median").as_double(), 0) << " | "
           << f(b.at("astar_settled_median").as_double(), 0) << " |\n";
    }
    md << "\n";

    // ---- dispatch
    md << "## Dispatch decision latency\n\n";
    md << "| Policy | Available couriers | Median (us) | p95 (us) | Mean (us) |\n|---|---:|---:|---:|---:|\n";
    for (const auto& x : D.at("results").as_array()) {
        md << "| " << x.at("policy").as_string() << " | " << x.at("couriers").as_int() << " | "
           << f(x.at("median_us").as_double()) << " | " << f(x.at("p95_us").as_double()) << " | "
           << f(x.at("mean_us").as_double()) << " |\n";
    }
    md << "\n";

    // ---- experiments
    if (!experiments_md.empty()) {
        std::ifstream in(experiments_md);
        if (in) {
            md << "## Dispatch policy comparison (experiment runner)\n\n";
            md << "Source: `" << experiments_md << "` (CSV/JSON alongside).\n\n";
            std::string line;
            bool first = true;
            while (std::getline(in, line)) {
                if (first && line.rfind("# ", 0) == 0) {  // drop the file title
                    first = false;
                    continue;
                }
                first = false;
                if (line.rfind("## ", 0) == 0) line = "#" + line;  // demote headings
                md << line << "\n";
            }
            md << "\n";
        }
    }
    md << kEnd;

    // Splice into the existing file, preserving hand-written text.
    std::string existing;
    {
        std::ifstream in(out_path);
        if (in) existing.assign(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
    }
    if (existing.find(kBegin) == std::string::npos || existing.find(kEnd) == std::string::npos) {
        existing = default_prose();
    }
    const auto b = existing.find(kBegin);
    const auto e = existing.find(kEnd) + std::string(kEnd).size();
    const std::string result = existing.substr(0, b) + md.str() + existing.substr(e);
    json::write_file(out_path, result);
}

}  // namespace dispatchlab
